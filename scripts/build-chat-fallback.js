const fs = require('node:fs');
const path = require('node:path');
const createFallback = require('../lib/guest-fallback');
const root = path.join(__dirname, '..');
const guide = JSON.parse(fs.readFileSync(path.join(root, 'data/guide-knowledge.json'), 'utf8'));
const output = '// Generated by npm run build:chat from guide-knowledge.json and lib/guest-fallback.js.\n' +
  '(function(root){root.ExtayChatFallback=(' + createFallback.toString().replace(/\r\n/g, '\n') + ')(' + JSON.stringify(guide) + ');})(globalThis);\n';
const file = path.join(root, 'assets/chat-fallback.js');
if (process.argv.includes('--check')) {
  if (!fs.existsSync(file) || fs.readFileSync(file, 'utf8').replace(/\r\n/g, '\n') !== output) {
    console.error('Browser fallback is stale. Run npm run build:chat.');
    process.exitCode = 1;
  }
} else {
  fs.writeFileSync(file, output);
  console.log('Built the browser fallback from current guide knowledge.');
}
